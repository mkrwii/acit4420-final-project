from classes import Flexibility
import random
DATA_FOLDER = "./data"

COMPANIES = ["SolRuta", "Camino Express", "CostaLink", "VerdeBus", "NocheVia", "RápidoBus", "TransEspaña", "ViajeFácil", "BusDirecto", "AutobúsPlus"] #Generated by VS Code Autocomplete
DESTINATIONS = ["Barcelona", "Valencia", "Seville", "Malaga", "Granada", "Cordoba", "Bilbao", "San Sebastian", "Zaragoza", "Alicante", "Murcia", "Salamanca", "Toledo", "Santiago de Compostela", "Cadiz"] #Generated by VS Code Autocomplete

def write_data_to_file(data, filename="offers.csv"):
    """
    takes a list of strings, and writes each string to a new line in the file provided.
    """
    with open(f"{DATA_FOLDER}/{filename}", "w") as f:
        for line in data:
            f.write(line + "\n")

def combine_destinations(destinations):
    """
    returns a list of tuples, where each tuple contains a destination and a list of all other destinations,
    a simpler way to represent what an Origin-Destination matrix would show.
    Input list [A, B, C] would return [(A, [B, C]), (B, [A, C]), (C, [A, B])]
    """
    combined = []
    for i in range(len(destinations)):
        combined.append((destinations[i], [j for j in destinations if j != destinations[i]]))
    return combined

def populate_offers(combined):
    bulk_data = []
    for origin, destinations in combined:
        for destination in destinations:
            for company in COMPANIES:
                price = round(random.uniform(10, 100), 2)
                transfers = random.randint(0, 3)
                duration = round(random.uniform(1, 10), 1)
                luggage = random.randint(0, 5)
                flexibility = random.choice(list(Flexibility))
                bulk_data.append(f"{company},{origin},{destination},{price},{transfers},{duration},{luggage},{flexibility.name}")
    return bulk_data


def main():
    combined = combine_destinations(DESTINATIONS)
    bulk_data = populate_offers(combined)
    try:
        write_data_to_file(bulk_data)
    except Exception as e:
        print(f"Error occurred while writing data to file: {e}")

if __name__ == "__main__":
    main()